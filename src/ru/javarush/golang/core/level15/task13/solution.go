package main

/*
= Задача №13. Сортировка показаний =
Вы пишете маленькую утилиту для техников: они выгружают набор чисел (например, показания датчиков), а вам нужно вывести их в аккуратном отсортированном виде. Главное требование — стабильность вывода: один и тот же ввод должен давать один и тот же порядок строк, без сюрпризов.
Программа читает целое число n, а затем n целых чисел. Нужно отсортировать числа по возрастанию и вывести их в одной строке через пробел. Если n == 0, выведите пустую строку (только перевод строки).
Требования:
• Программа должна прочитать из stdin целое число n, затем прочитать ровно n целых чисел.
• Программа должна отсортировать считанные числа по возрастанию, используя sort.Ints или slices.Sort, без ручной реализации алгоритма сортировки.
• Сортировка должна выполняться in-place (над тем же слайсом), без создания отдельной структуры данных для “пересортировки”.
• Программа должна вывести числа строго в отсортированном порядке в одной строке, разделяя их ровно одним пробелом, и обязательно завершить вывод переводом строки.
• Если n равно 0, программа должна вывести пустую строку (то есть только перевод строки), не пытаясь читать числа и не печатая лишних пробелов.
*/

import (
	"bufio"
	"fmt"
	"os"
	"sort"
)

func main() {
	in := bufio.NewReader(os.Stdin)
	out := bufio.NewWriter(os.Stdout)
	defer out.Flush()

	var n int
	fmt.Fscan(in, &n)

	if n == 0 {
		// По условию: для n=0 печатаем только перевод строки и ничего не читаем дальше.
		fmt.Fprintln(out)
		return
	}

	nums := make([]int, n)
	for i := 0; i < n; i++ {
		fmt.Fscan(in, &nums[i])
	}

	// TODO: Отсортируйте nums по возрастанию стандартной библиотекой (sort.Ints или slices.Sort), in-place (над этим же слайсом), без использования map.
	sort.Ints(nums)

	// Вывод без лишних пробелов: один пробел между числами + перевод строки в конце.
	fmt.Fprint(out, nums[0])
	for i := 1; i < len(nums); i++ {
		fmt.Fprint(out, " ", nums[i])
	}
	fmt.Fprintln(out)
}