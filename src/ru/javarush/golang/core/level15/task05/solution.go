package main

/*
= Задача №5. Возрастная база =
Вы поддерживаете крошечную “базу возрастов” внутри программы: это справочник map[string]int, где по имени можно узнать возраст. И чтобы никто не перепутал “возраст 0” с “такого человека нет”, в справочнике специально есть хотя бы одна запись со значением 0 (например, младенец).
Программа читает одно слово personName. Если ключ есть в справочнике, выведите строку age: <число>. Если ключа нет — выведите no such person.
Требования:
• В коде программы должен быть заранее задан `map[string]int` с несколькими парами (имя → возраст), при этом весь map не вводится пользователем.
• В справочнике должна быть как минимум одна запись, у которой значение возраста равно `0`, чтобы проверить отличие “ключ есть” от “ключа нет”.
• Программа должна прочитать одно слово `personName` с помощью `fmt.Scan`.
• Возраст должен извлекаться только через конструкцию `v, ok := ages[personName]`, чтобы корректно различать отсутствие ключа и zero value.
• Логика выбора результата должна основываться на значении `ok` (ключ существует/не существует), а не на сравнении `v` с `0` или другими числами.
*/

import "fmt"

func main() {
	// Справочник задан заранее (не вводится пользователем).
	ages := map[string]int{
		// TODO: добавьте несколько пар (имя → возраст); обязательно добавьте хотя бы одну запись с возрастом 0
		"Вася":     20,
		"Петя":     12,
		"Юля":      0,
	}

	var personName string
	fmt.Scan(&personName)

	// TODO: найдите возраст по имени в map через ok-идиому, чтобы различать:
	// TODO: 1) ключа нет (ok == false)
	// TODO: 2) ключ есть, но возраст может быть 0 (ok == true, age == 0)
	// TODO: в зависимости от ok выведите либо "age: <число>", либо "no such person" (точный формат)
	if v, ok := ages[personName]; ok {
	    fmt.Printf("age: %d", v)
	} else {
	    fmt.Print("no such person")
	}
}