package main

/*
= Задача №9. Касса по категориям =
Вы делаете маленький отчёт для киоска: покупки приходят как пары “категория товара” и “сумма”. Категории повторяются, поэтому нужно аккуратно накапливать суммы по каждой категории в map, а потом получить общий итог — сколько денег прошло через кассу вообще.
Программа читает число n, затем n пар: categoryName (одно слово) и amount (целое число). Данные накапливаются в map[string]int, где по ключу категории хранится сумма всех amount для этой категории.
После чтения всех пар программа обходит map через for range и считает общий итог — сумму всех значений, а затем выводит эту сумму одним числом.
Требования:
• Программа должна прочитать целое число n, затем ровно n пар значений (categoryName как одно слово и amount как целое число) с использованием fmt.Scan или fmt.Fscan.
• Программа должна хранить накопленные суммы по категориям в структуре map[string]int, где ключ — имя категории, значение — сумма всех amount для этой категории.
• Если категория встречается несколько раз, программа должна увеличивать накопленную сумму (+= amount), а не перезаписывать её.
• После чтения всех пар программа должна вычислить общий итог как сумму всех значений map, используя обход map через for range (по значениям или по k, v).
• Программа должна вывести ровно одно целое число — общий итог — и перевод строки; при n = 0 должна быть выведена 0.
*/

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	in := bufio.NewReader(os.Stdin)
	out := bufio.NewWriter(os.Stdout)
	defer out.Flush()

	var n int
	fmt.Fscan(in, &n)

	sums := make(map[string]int)

	for i := 0; i < n; i++ {
		var category string
		var amount int
		fmt.Fscan(in, &category, &amount)

		// TODO: Реализуйте корректное накопление суммы по категориям (повторы должны увеличивать сумму, а не затирать предыдущее значение).
		sums[category] = sums[category] + amount
	}

	total := 0
	for _, v := range sums {
		total += v
	}

	fmt.Fprintln(out, total)
}