package main

/*
= Задача №15. Частоты для отчёта =
Вы делаете отчёт по логам: на вход идёт поток слов до конца файла (EOF), и нужно посчитать, сколько раз встречается каждое слово. Затем — вывести в порядке убывания частоты, чтобы самые “шумные” слова оказались сверху. А чтобы отчёт всегда был одинаковым при равных частотах, нужен второй критерий: алфавитный порядок слова.
Программа читает слова из stdin до EOF, считает частоты в map[string]int, а потом печатает все уникальные слова и их частоты: сначала по убыванию частоты, а при равенстве частоты — по возрастанию слова. Формат строки: word frequency.
Требования:
• Программа должна читать последовательность слов из stdin в цикле с fmt.Scan и завершать чтение при возникновении ошибки ввода (в т.ч. EOF).
• Для каждого прочитанного слова программа должна увеличивать счётчик в map[string]int, чтобы получить частоту каждого уникального слова.
• Перед печатью программа должна собрать все уникальные слова (ключи map) в отдельный слайс строк.
• Слайс слов должен быть отсортирован с помощью sort.Slice так, чтобы первично слова шли по убыванию частоты, а при равенстве частоты — по возрастанию слова (алфавитно).
• Программа должна печатать результат, проходя по отсортированному слайсу слов, и выводить по одной строке на слово в формате: `word frequency`.
*/

import (
	"fmt"
	"sort"
)

func main() {
	freq := make(map[string]int)

	// Читаем слова до первой ошибки ввода (в т.ч. EOF).
	for {
		var w string
		if _, err := fmt.Scan(&w); err != nil {
			break
		}
		freq[w]++
	}

	// Собираем ключи map в отдельный слайс, чтобы не зависеть от порядка map.
	words := make([]string, 0, len(freq))
	for w := range freq {
		words = append(words, w)
	}

	// Временная (неполная) сортировка: только по алфавиту.
	// TODO: Реализуйте сортировку words по убыванию частоты, а при равенстве частоты — по возрастанию слова.
	//sort.Strings(words)
	sort.Slice(words, func(i, j int) bool {
	    wi, wj := words[i], words[j]
	    fi, fj := freq[wi], freq[wj]
	    if fi != fj {
	        return fi > fj
	    }
	    return wi < wj
	})

	// Печать строго по слайсу (не через range по map).
	for _, w := range words {
		fmt.Printf("%s %d\n", w, freq[w])
	}
}