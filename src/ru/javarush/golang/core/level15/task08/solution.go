package main

/*
= Задача №8. Заметки в консоли =
Вы пишете мини‑хранилище заметок: ключ — короткое имя заметки, значение — одно слово. Всё хранится в map[string]string. Команды приходят как в простом терминале, и на каждую команду нужно печатать ровно одну строку результата.
Программа читает число q, затем обрабатывает q команд:
- set key value — записывает значение; если введено значение "-", в map нужно сохранить пустую строку "" (пустая строка считается валидным значением),
- get key — печатает value: "<строка>", если ключ существует, иначе no such key (кавычки обязательны),
- exists key — печатает true или false (только факт наличия ключа),
- del key — печатает deleted, если ключ существовал, иначе missing.
Требования:
• Программа должна создать изначально пустую map[string]string через make и использовать её для хранения пар key → value.
• Программа должна прочитать число q и затем выполнить цикл for, в котором обрабатывается ровно q команд (по одной команде за итерацию).
• При команде `set key value` программа должна записывать пару в map; если value равно `-`, в map должно быть сохранено значение пустой строки "" (пустая строка считается валидным значением, ключ при этом считается существующим).
• При команде `get key` программа должна получать значение только через `v, ok := notes[key]`; если ok == false — печатать `no such key`, иначе печатать `value: "<строка>"` (кавычки обязательны) так, чтобы пустая строка была видна в выводе (например, через форматирование `%q`).
• При команде `exists key` программа должна проверять наличие ключа через `_, ok := notes[key]` и печатать ровно `true` или `false` в зависимости от ok.
• При команде `del key` программа должна сначала определить существование ключа через `_, ok := notes[key]`, и только затем вызывать delete; если ключ существовал — печатать `deleted`, иначе — `missing`.
*/

import "fmt"

func main() {
	notes := make(map[string]string) // хранилище заметок key -> value

	var q int
	fmt.Scan(&q)

	for i := 0; i < q; i++ {
		var cmd string
		fmt.Scan(&cmd)

		switch cmd {
		case "set":
			var key, value string
			fmt.Scan(&key, &value)

			// TODO: Реализуйте сохранение заметки в map notes по ключу key.
			// TODO: Если value равно "-", сохраните пустую строку "" (это валидное значение).
			// TODO: Убедитесь, что эта команда печатает ровно одну строку результата (пустую строку).
			if value == "-" {
			    notes[key] = ""
			} else {
			    notes[key] = value
			}

			fmt.Println("")

		case "get":
			var key string
			fmt.Scan(&key)

			// TODO: Реализуйте получение значения ТОЛЬКО через ok-идиому: v, ok := notes[key].
			// TODO: Если ключа нет — печатайте "no such key".
			// TODO: Если ключ есть — печатайте: value: "<строка>" (кавычки обязательны).
			// TODO: Сделайте так, чтобы пустая строка была видна в выводе (например, через форматирование %q).
			v, ok := notes[key]
			if !ok {
			    fmt.Println("no such key")
			} else {
                fmt.Printf("value: %q\n", v)
            }

		case "exists":
			var key string
			fmt.Scan(&key)

			// TODO: Реализуйте проверку существования ключа через ok-идиому: _, ok := notes[key].
			// TODO: Печатайте ровно true или false в зависимости от наличия ключа.
			_, ok := notes[key]
			fmt.Println(ok)

		case "del":
			var key string
			fmt.Scan(&key)

			// TODO: Реализуйте удаление: сначала проверьте существование ключа через ok-идиому.
			// TODO: Если ключ существовал — удалите его через delete(notes, key) и выведите "deleted".
			// TODO: Если ключа не было — выведите "missing".
			_, ok := notes[key]
			if ok == true {
			    delete(notes, key)
			    fmt.Println("deleted")
			} else {
			    fmt.Println("missing")
			}
		}
	}
}