package main

/*
= Задача №17. Уникальные команды =
Вы разбираете лог голосового помощника: пользователь произносит команды, а вам нужно понять, сколько разных (уникальных) команд вообще встретилось. Команды приходят как отдельные слова без пробелов, и повторов может быть много.
Программа читает число n, затем ровно n слов. Нужно посчитать количество различных слов и вывести это число.
Для хранения уникальных значений используйте множество на базе map[string]struct{}: это “настоящий set‑стиль” в Go, без лишней памяти под bool.
Требования:
• Программа должна прочитать из stdin целое число n, затем прочитать ровно n слов (строк без пробелов).
• Программа должна выполнять добавление слов в множество в цикле, который исполняется ровно n итераций (не “до конца ввода” и не по другому условию).
• Для хранения уникальных слов программа должна использовать структуру данных uniqueWords типа map[string]struct{} (set-подход в Go).
• Каждое считанное слово должно добавляться в множество операцией присваивания вида uniqueWords[word] = struct{}{}.
• После обработки всех n слов программа должна вывести количество различных слов как len(uniqueWords) в stdout.
*/

import "fmt"

func main() {
	var n int
	fmt.Scan(&n)

	uniqueWords := make(map[string]struct{}) // set на map: struct{} не занимает память под значение

	for i := 0; i < n; i++ {
		var word string
		fmt.Scan(&word)

		// TODO: Добавьте считанное слово в множество uniqueWords (set-паттерн на map[string]struct{})
		uniqueWords[word] = struct{}{}
	}

	fmt.Print(len(uniqueWords))
}