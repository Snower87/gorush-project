package main

/*
= Задача №10. Самый ранний клиент =
У вас есть справочник клиентов: каждому числовому id соответствует имя. Для отчёта нужно найти “самого раннего” — клиента с минимальным id. Порядок чтения может быть каким угодно, но результат должен быть правильным всегда.
Программа читает число n (n >= 1), затем n пар: clientID (int) и clientName (одно слово). Данные сохраняются в map[int]string, чтобы по id можно было получить имя.
Затем программа находит минимальный ключ clientID среди всех ключей map и выводит minID и соответствующее ему имя через пробел.
Требования:
• Программа должна прочитать целое число n (n >= 1), затем прочитать n пар значений: clientID типа int и clientName (одно слово) из стандартного ввода.
• Программа должна сохранить все считанные пары в структуру данных типа map[int]string, где ключ — clientID, значение — clientName.
• Программа должна найти минимальный clientID среди всех ключей карты, выполняя обход map и явное сравнение ключей (например, через условие вида if id < minID).
• Алгоритм поиска минимального id не должен опираться на порядок обхода map и не должен использовать идею “первого элемента map” как минимального (ответ должен быть корректным при любом порядке итерации).
*/

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	in := bufio.NewReader(os.Stdin)

	var n int
	fmt.Fscan(in, &n)

	clients := make(map[int]string, n)
	for i := 0; i < n; i++ {
		var id int
		var name string
		fmt.Fscan(in, &id, &name)
		clients[id] = name
	}

	// TODO: Найдите минимальный id среди ключей clients обходом map и явным сравнением ключей.
	// TODO: Нельзя опираться на порядок итерации по map: он не гарантирован.

	var minID int
	var minName string
	var first = true

	// Временная (неправильная) логика: берём первый попавшийся элемент.
	// Это нужно заменить на корректный поиск минимума.
	for id, name := range clients {
	    if first {
	        minID = id
	        minName = clients[id]
	        first = false
	        continue
	    }
	    if id < minID {
    		minID = id
    		minName = name
	    }
	}

	fmt.Printf("%d %s\n", minID, minName)
}