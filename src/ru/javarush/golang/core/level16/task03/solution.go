package main

/*
= Задача №3. Пропуск числа =
Вообразите турникет на входе в закрытую зону: он получает один токен и пытается понять, число это или нет. Если токен действительно число, проход разрешён — и можно вывести “успех” плюс распознанное значение. Если токен не число, это не “катастрофа”, а нормальная ветка сценария: нужно вывести “ошибка” и показать, что за ошибка получилась и какого она типа.
Программа читает из stdin один токен numberToken (строку) и пытается преобразовать его в целое число через strconv.Atoi. Главный критерий решения — err: при успехе он nil, при ошибке — не nil.
Требования:
• Программа должна прочитать из stdin ровно один токен-строку `numberToken` (без чтения дополнительных значений).
• Программа должна пытаться преобразовать `numberToken` в целое число строго вызовом `strconv.Atoi(numberToken)` и получить `(n, err)`.
• Программа должна выбирать ветку выполнения только по условию `err == nil` (успех) или `err != nil` (ошибка), без дополнительных проверок содержимого строки.
• Если `err == nil`, программа должна вывести в первой строке `OK`, а затем вывести распознанное целое значение `n`.
• Если `err != nil`, программа должна вывести в первой строке `ERROR`, затем вывести само значение `err` (через `fmt.Println(err)` или формат `%v`) без анализа текста `err.Error()`.
• Если `err != nil`, программа должна дополнительно напечатать тип `err` с помощью `fmt.Printf("%T", err)` (после строки `ERROR`).
*/

import (
	"fmt"
	"os"
	"strconv"
)

func main() {
	var numberToken string
	fmt.Fscan(os.Stdin, &numberToken)

	n, err := strconv.Atoi(numberToken)

	// TODO: Реализуйте ветвление строго по err (err == nil / err != nil) и корректный вывод по формату задачи.
	if err == nil {
		fmt.Println("OK")
		// TODO: Выведите распознанное целое число n во второй строке.
		fmt.Println(n)
	} else {
		fmt.Println("ERROR")
		// TODO: Выведите само значение err отдельной строкой (через fmt.Println(err) или %v), без анализа err.Error().
		fmt.Println(err)
		// TODO: Выведите тип err с помощью fmt.Printf("%T\n", err).
		fmt.Printf("%T\n", err)
	}
}