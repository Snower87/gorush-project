package main

/*
= Задача №19. Алфавитный счётчик =
Вы пишете анализатор текста для маленького отчёта: нужно не просто посчитать, сколько раз встречается каждое слово, но и вывести результат в алфавитном порядке, чтобы сравнивать отчёты между запусками было удобно. А map сам по себе печатать нельзя — порядок обхода у него непредсказуемый.
Программа читает n, затем n слов. Считает частоты в map[string]int. Потом выводит:
в первой строке число k — количество различных слов,
далее k строк: слово пробел количество, в лексикографическом порядке слов (по возрастанию).
Для стабильного вывода соберите ключи в слайс, отсортируйте и печатайте по отсортированным ключам.
Требования:
• Программа должна прочитать целое число n, затем прочитать ровно n слов (строк без пробелов) из stdin.
• Программа должна использовать счётчик counts типа map[string]int, где ключ — слово, значение — количество его вхождений.
• При чтении очередного слова программа должна увеличивать частоту строго операцией counts[word]++.
• В первой строке вывода программа должна напечатать k — количество различных слов, вычисленное как len(counts).
• Программа должна собрать все ключи counts в слайс keys (желательно make([]string, 0, len(counts))), отсортировать его через sort.Strings и печатать статистику строго в порядке отсортированных ключей.
*/

import (
	"bufio"
	"fmt"
	"os"
	"sort"
)

func main() {
	in := bufio.NewReader(os.Stdin)
	out := bufio.NewWriter(os.Stdout)
	defer out.Flush()

	var n int
	fmt.Fscan(in, &n)

	// Счётчик частот: ключ — слово, значение — сколько раз встретилось.
	counts := make(map[string]int)

	for i := 0; i < n; i++ {
		var word string
		fmt.Fscan(in, &word)

		// TODO: увеличьте частоту слова строго операцией counts[word]++
		// Сейчас намеренно неверно: повторяющиеся слова перезаписываются.
		counts[word]++
	}

	// Для стабильного вывода нужны ключи и сортировка.
	keys := make([]string, 0, len(counts))

	// TODO: соберите все ключи counts в keys
	for k := range counts {
	    keys = append(keys, k)
	}
	// (сейчас keys остаётся пустым, сортировка ничего не делает)
	sort.Strings(keys)

	fmt.Fprintln(out, len(counts))

	// TODO: выведите ровно len(counts) строк в лексикографическом порядке слов
	// TODO: формат строки: слово + пробел + количество
	// Сейчас намеренно неверно: порядок нестабилен и количество не выводится.
	for _, k := range keys {
		fmt.Fprintln(out, k, counts[k])
	}
}