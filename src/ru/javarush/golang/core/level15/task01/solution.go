package main

/*
= Задача №1. Карманный переводчик =
Представьте, что вы делаете крошечный офлайн‑переводчик для туриста: всего три слова, зато работают мгновенно и без интернета. Внутри программы уже “прошит” мини‑словарь переводов «английское слово → перевод».
Программа получает на вход одно английское слово и должна вывести его перевод. А чтобы турист поверил, что это правда “мини”, сразу после перевода выведите, сколько всего записей хранится в вашем словаре.
Считайте, что введённое слово всегда есть среди ключей словаря — проверять отсутствие не нужно.
Требования:
• В программе должен быть создан словарь переводов типа map[string]string через литерал map[string]string{...} (использование make для словаря запрещено).
• Программа должна считать одно английское слово из stdin с помощью fmt.Scan или fmt.Fscan.
• Перевод должен извлекаться выражением dictionary[inputWord] без дополнительной проверки наличия ключа.
• Программа должна вывести перевод считанного слова в первой строке, а во второй строке вывести количество записей в словаре как len(dictionary).
• В программе не должны использоваться циклы и не должны объявляться функции, кроме func main().
*/

import "fmt"

func main() {
	// Мини-словарь "английское слово -> перевод" (обязательно литералом, без make).
	dictionary := map[string]string{
		"hello":  "привет", // TODO: Заполните перевод для слова "hello".
		"bye":    "пока", // TODO: Заполните перевод для слова "bye".
		"thanks": "спасибо", // TODO: Заполните перевод для слова "thanks".
	}

	var inputWord string
	// TODO: Считайте одно английское слово из stdin в переменную inputWord с помощью fmt.Scan или fmt.Fscan.
	fmt.Scan(&inputWord)

	// По условию слово всегда есть в словаре — ok-проверка запрещена/не нужна.
	fmt.Println(dictionary[inputWord])
	fmt.Println(len(dictionary))
}