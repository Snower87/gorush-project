package main

/*
= Задача №12. Бонус всем словам =
Вы анализируете чат: сначала считаете, сколько раз встретилось каждое слово, а потом запускаете “акцию” — всем словам добавляется по 10 к счётчику (например, как будто пришли ещё 10 сообщений с каждым словом). Это упражнение важно из‑за ловушки: при range по map значение v — копия, и если просто менять v, в карте ничего не обновится.
Программа читает число n (n >= 1), затем n слов. Постройте map[string]int частот. Потом прочитайте слово queryWord (оно гарантированно встречалось среди первых n слов). Далее обойдите map через for range и увеличьте каждый счётчик на 10, записывая обновлённое значение обратно по ключу.
В конце выведите два числа: количество уникальных слов и обновлённый счётчик для queryWord.
Требования:
• Программа должна прочитать целое число n (n >= 1), затем n слов, затем слово queryWord.
• Программа должна построить частотный словарь words → count, используя структуру данных map[string]int и увеличивая счётчик при чтении каждого из n слов.
• После построения словаря программа должна выполнить обход map через цикл for range.
• Внутри обхода for range программа должна увеличить каждый счётчик на 10 и записать обновлённое значение обратно в map по ключу (т.е. обновление должно делаться через присваивание вида counts[k] = v + 10).
• Решение не должно полагаться на какой-либо порядок обхода map (порядок итерации не используется для вычислений и вывода результата).
*/

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	in := bufio.NewReader(os.Stdin)

	var n int
	fmt.Fscan(in, &n)

	counts := make(map[string]int)
	for i := 0; i < n; i++ {
		var w string
		fmt.Fscan(in, &w)

		// TODO: реализуйте корректный подсчёт частот слов в map (при повторе слова счётчик должен увеличиваться)
		v, ok := counts[w]
		counts[w]++
	}

	var queryWord string
	fmt.Fscan(in, &queryWord)

	// TODO: увеличьте каждый счётчик на 10 и обязательно запишите обновлённое значение обратно в map по ключу (не пытайтесь менять только переменную v)
	for k, v := range counts {
		counts[k] = counts[k] + 10
	}

	fmt.Printf("%d %d\n", len(counts), counts[queryWord])
}